"""Excel risk report (openpyxl) and a markdown findings memo."""

from __future__ import annotations

from pathlib import Path

import pandas as pd
from openpyxl import Workbook
from openpyxl.drawing.image import Image as XLImage
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from openpyxl.utils import get_column_letter

HEADER_FILL = PatternFill("solid", fgColor="1F3A5F")
HEADER_FONT = Font(bold=True, color="FFFFFF")
TITLE_FONT = Font(bold=True, size=14)
THIN = Border(bottom=Side(style="thin", color="D9D9D9"))

PCT_COLS = ("rate", "pct", "ltv", "dti", "pti", "approval", "overlay")
USD_COLS = ("balance", "amount", "loss", "chargeoff", "recover", "margin", "profit", "forgone", "avoided",
            "actual", "vintage_curve", "roll_rate", "forecast", "nco", "flow")


def _fmt_for(col: str) -> str | None:
    c = col.lower()
    if c in ("auc", "gini", "ks", "psi_vs_dev", "woe", "iv"):
        return "0.000"
    if any(k in c for k in PCT_COLS):
        return "0.00%"
    if any(k in c for k in USD_COLS):
        return '"$"#,##0'
    return None


def write_table(ws, df: pd.DataFrame, start_row: int = 3, title: str | None = None, note: str | None = None) -> int:
    if title:
        ws.cell(row=1, column=1, value=title).font = TITLE_FONT
    if note:
        ws.cell(row=2, column=1, value=note).font = Font(italic=True, color="595959")
    for j, col in enumerate(df.columns, start=1):
        c = ws.cell(row=start_row, column=j, value=str(col))
        c.fill, c.font = HEADER_FILL, HEADER_FONT
        c.alignment = Alignment(horizontal="center", wrap_text=True)
    for i, row in enumerate(df.itertuples(index=False), start=start_row + 1):
        for j, val in enumerate(row, start=1):
            if isinstance(val, pd.Timestamp):
                val = val.to_pydatetime()
            cell = ws.cell(row=i, column=j, value=val)
            cell.border = THIN
            fmt = _fmt_for(df.columns[j - 1])
            if fmt and isinstance(val, (int, float)):
                cell.number_format = fmt
            elif hasattr(val, "year"):
                cell.number_format = "mmm yyyy"
    for j, col in enumerate(df.columns, start=1):
        width = max(len(str(col)), *(len(f"{v:,.2f}") if isinstance(v, float) else len(str(v)) for v in df.iloc[:, j - 1])) \
            if len(df) else len(str(col))
        ws.column_dimensions[get_column_letter(j)].width = min(max(width + 2, 10), 38)
    ws.freeze_panes = ws.cell(row=start_row + 1, column=1)
    return start_row + len(df) + 1


def build_workbook(path: Path, sheets: dict[str, tuple[pd.DataFrame, str]], kpis: list[tuple[str, str]],
                   images: list[Path]) -> Path:
    wb = Workbook()
    dash = wb.active
    dash.title = "Dashboard"
    dash["A1"] = "Powersports Loan Portfolio – Credit Risk Dashboard"
    dash["A1"].font = Font(bold=True, size=16)
    dash["A2"] = "Synthetic data. All figures generated by the pipeline in this repository."
    dash["A2"].font = Font(italic=True, color="595959")
    for i, (label, value) in enumerate(kpis, start=4):
        dash.cell(row=i, column=1, value=label).font = Font(bold=True)
        dash.cell(row=i, column=2, value=value).alignment = Alignment(horizontal="right")
    dash.column_dimensions["A"].width = 46
    dash.column_dimensions["B"].width = 18
    anchor_row = 4
    for k, img_path in enumerate(images):
        img = XLImage(str(img_path))
        img.width, img.height = img.width * 0.42, img.height * 0.42
        col = "D" if k % 2 == 0 else "N"
        dash.add_image(img, f"{col}{anchor_row}")
        if k % 2 == 1:
            anchor_row += 25
    for name, (df, note) in sheets.items():
        ws = wb.create_sheet(name[:31])
        write_table(ws, df, title=name, note=note)
    path.parent.mkdir(parents=True, exist_ok=True)
    wb.save(path)
    return path


def write_memo(path: Path, m: dict) -> Path:
    text = f"""# Credit Risk Portfolio Review – Findings Memo

*Auto-generated by `python -m credit_risk.pipeline` on synthetic data (as of {m['as_of']}).*

## Portfolio snapshot
- **{m['active_accounts']:,} active accounts, {m['balance']} outstanding** across motorcycles, ATVs, side-by-sides and watercraft.
- **30+ DPD delinquency: {m['dq30']}** of balance; **annualized net charge-off rate: {m['nco']}** (trailing 3-month average).
- Losses track the simulated unemployment rate with a lag: unemployment rose through 2024, net charge-offs peaked in 2025 as those stressed accounts rolled to charge-off, and both have eased in 2026.

## Where the risk sits (segmentation)
- FICO is the dominant driver: seasoned net loss rate runs from **{m['loss_fico_low']} (<620)** to **{m['loss_fico_high']} (740+)**.
- Collateral coverage matters almost as much: **105%+ LTV** loans lose **{m['loss_ltv_high']}** vs **{m['loss_ltv_low']}** under 80% LTV — backend add-ons that push LTV above 100% deserve tighter limits for thin-down-payment deals.
- Longer terms carry more loss: 72-month loans lose {m['loss_72']} vs {m['loss_36']} for 36-month.

## Application scorecard
- Logistic-regression scorecard on WoE-binned {m['features']} (features with information value ≥ 0.02).
- **Out-of-time AUC {m['oot_auc']:.3f}, Gini {m['oot_gini']:.3f}, KS {m['oot_ks']:.3f}**; score PSI dev → OOT **{m['psi']:.3f}** (stable, < 0.10).

## Strategy recommendation
- A score cutoff of **{m['cutoff']}** keeps **{m['approval']}** of volume, cuts the approved bad rate from **{m['bad_all']} to {m['bad_cut']}**, and avoids **{m['loss_avoided']}** of net losses on the OOT population for **{m['margin_forgone']}** of forgone margin — a net profit lift of **{m['profit_lift']}**.
- Higher cutoffs lift profit slightly further but drop approvals below 85%, which would hurt dealer relationships and volume.

## Loss forecast (existing book, next 12 months)
- Vintage-curve method: **{m['fc_vintage']}**; roll-rate method: **{m['fc_roll']}** of net charge-offs.
- Backtest (forecast made {m['bt_as_of']}): vintage-curve error **{m['bt_err_vc']}**, roll-rate error **{m['bt_err_rr']}** vs actual {m['bt_actual']}. Both over-forecast, consistent with unemployment easing after the forecast date while the methods assumed recent loss levels would persist; tying the overlay to an economic scenario is the natural next refinement.

## Limitations
- Synthetic data; booked loans only (no reject inference); simplified recoveries (booked at charge-off) and margin assumptions (see `config.py`).
"""
    path.write_text(text)
    return path
